"""Writes diagrams/fidentis-route.mmd: the Fidentis route (data/routes/fidentis.json) with the durations of one
default order (4 telescopes, so 4 primary parts) nested alone, from data/generator/fidentis.json. Rerun after a
change of durations:

    uv run python diagrams/fidentis_route.py
"""

import json
from pathlib import Path

from simulation.carrier_generator import CarrierGeneratorParams, generate_carrier_instance
from simulation.io.json_loader import read_model
from simulation.model.compiled import compile_instance

ROOT = Path(__file__).parents[1]
OUT = ROOT / "diagrams" / "fidentis-route.mmd"


def main() -> None:
    params = read_model(ROOT / "data/generator/fidentis.json", CarrierGeneratorParams)
    alone = params.model_copy(update={"n_orders": 1, "count_range": (4, 4), "count_lognormal": None,
                                      "release_range": (0, 0), "due_date_tightness": ()})
    inst = generate_carrier_instance(alone)
    ci = compile_instance(inst)
    route = json.loads((ROOT / "data/routes/fidentis.json").read_text(encoding="utf-8"))
    runs = {r.step for r in inst.runs}

    def parts(op: dict) -> list[str]:
        """'setup 95 @print1 (attended)', ... for every compiled operation executing route operation op."""
        names = [op["id"], f"{op['id']}/setup", f"{op['id']}/removal"]
        keys = [k for k in ci.op_keys if k[1] in names and k[0] in {c.id for c in inst.carriers}]
        if op["step"] in runs:  # a run of nesting: owner is the run, ids are setup, step, removal
            keys = [k for k in ci.op_keys if k[0] in {r.id for r in inst.runs if r.step == op["step"]}]
        if not keys:
            keys = [(inst.orders[0].id, op["id"])]
        out = []
        for k in keys:
            o = ci.op_index[k]
            where = (f"@{', '.join(ci.machine_ids[m] for m, _ in ci.options[o])}" if ci.options[o] else "worker")
            p = ci.fixed_duration[o] if ci.fixed_duration[o] is not None else max(p for _, p in ci.options[o])
            shares = ", ".join(f"{s.kind} {s.length}" if s.length else s.kind for s in ci.shares[o])
            part = k[1].split("/")[-1] if "/" in k[1] or k[1] in ("setup", "removal") else "main"
            out.append(f"{part} {p} {where}" + (f" ({shares})" if shares else " (unattended)" if ci.options[o] else ""))
        return out

    lines = ["%% generated by diagrams/fidentis_route.py from data/routes/fidentis.json and",
             "%% data/generator/fidentis.json: one order of 4 telescopes nested alone; minutes",
             "flowchart LR"]
    for op in route:
        sb = params.s_batch_steps.get(op["step"])
        tag = f"<br/><i>s-batch, setup {sb.setup}" + (f", max {sb.capacity}" if sb and sb.capacity else "") + "</i>" \
            if sb else ""
        scope = op.get("scope", "order")
        body = "<br/>".join(parts(op))
        lines.append(f'  {op["id"]}["<b>{op["id"]}</b> ({scope})<br/>{body}{tag}"]')
    for op in route:
        lines += [f"  {q} --> {op['id']}" for q in op.get("predecessors", ())]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
